/** @type {Map<string, string> | null} */
let table = null;

/**
 * The references by name, unpacked on first use
 * @returns {ReadonlyMap<string, string>}
 */
export function namedReferences() {
  if (table) return table;
  /** @type {Map<string, string>} */
  const unpacked = new Map();
  let point = 0;
  for (const group of PACKED.split(',')) {
    const colon = group.lastIndexOf(':');
    const [first, ...rest] = group.slice(colon + 1).split('+');
    point += Number.parseInt(first, 36);
    const text = String.fromCodePoint(point, ...rest.map(more => Number.parseInt(more, 36)));
    for (const name of group.slice(0, colon).split(' ')) {
      if (name.startsWith('*')) unpacked.set(name.slice(1), text);
      unpacked.set(`${name.replace(/^\*/, '')};`, text);
    }
  }
  table = unpacked;
  return table;
}
