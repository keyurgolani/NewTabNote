#!/usr/bin/env node

/**
 * Design token generator (#16).
 *
 *   npm run design-tokens   read design/quiet-atlas.tokens.json and write
 *                           css/design-tokens.css and js/design/tokens.generated.js
 *
 * It refuses to write when the source is malformed, or when any variant fails
 * js/design/contrast.js, or when a legacy dark pair no longer fails. Both outputs
 * are committed; test/design-tokens.test.js fails when they drift from the source.
 */

const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const ROOT_DIR = path.join(__dirname, '..');
const SOURCE_PATH = 'design/quiet-atlas.tokens.json';
const CSS_PATH = 'css/design-tokens.css';
const JS_PATH = 'js/design/tokens.generated.js';
const CONTRAST_PATH = 'js/design/contrast.js';

const TYPES = ['color', 'dimension', 'number', 'font-family', 'font-size', 'font-weight', 'line-height', 'letter-spacing', 'shadow', 'duration', 'easing'];
const STATUSES = ['approved', 'candidate'];
const KINDS = ['text', 'non-text', 'focus'];
const COLOR_AXIS = 'color';
const BASE_CELL = 'default';
// Color cells: scheme by contrast, plus forced colors over either
const COLOR_CELLS = ['light', 'dark', 'more', 'darkMore'];
const FORCED_CELL = 'forced';
// What `system` resolves to when a media query doesn't match
const NO_PREFERENCE = 'no-preference';
const PAIR_ID = /^[a-z0-9-]+\/[a-z0-9-]+\/[a-z0-9-]+$/;
const TOKEN_NAME = /^--[a-z0-9]+(?:-[a-z0-9]+)*$/;
const PX_LENGTH = /^\d*\.?\d+px$/;
const HEADER = 'Generated by `npm run design-tokens` (scripts/build-design-tokens.js) from\n'
  + 'design/quiet-atlas.tokens.json. Don\'t edit: change the source and regenerate.';

/**
 * Load js/design/contrast.js, the ES module that owns the color grammar
 */
async function loadDesign(root = ROOT_DIR) {
  return import(pathToFileURL(path.join(root, CONTRAST_PATH)).href);
}

function readSource(root = ROOT_DIR) {
  return JSON.parse(fs.readFileSync(path.join(root, SOURCE_PATH), 'utf8'));
}

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * A source value as { value } or { ref }, with its optional status, legacy, and note
 */
function entryOf(raw) {
  if (typeof raw === 'string') return { value: raw };
  return raw;
}

/**
 * Resolved variant values per dimension. `system` resolves through its media
 * query, so it isn't a variant value itself.
 */
function variantDimensions(dimensions) {
  const out = {};
  const defaults = {};
  for (const [name, dimension] of Object.entries(dimensions)) {
    if (dimension.system) {
      out[name] = dimension.values.filter(value => value !== dimension.system.value);
      defaults[name] = dimension.default;
    } else if (dimension.media && dimension.values.includes('system')) {
      out[name] = [NO_PREFERENCE, ...dimension.values.filter(value => value !== 'system')];
      defaults[name] = dimension.default === 'system' ? NO_PREFERENCE : dimension.default;
    } else {
      out[name] = [...dimension.values];
      defaults[name] = dimension.default;
    }
  }
  return { dimensions: out, defaults };
}

/**
 * Check the source and resolve it into the data js/design/contrast.js reads.
 * Throws one Error listing every problem.
 */
function compile(source, design) {
  const errors = [];
  const fail = message => errors.push(message);

  if (!isRecord(source)) throw new Error(`${SOURCE_PATH}: not an object`);
  if (typeof source.name !== 'string' || !source.name) fail('name: missing');
  if (!Number.isInteger(source.version) || source.version < 1) fail('version: not a positive integer');
  for (const field of ['axes', 'dimensions', 'rules', 'tokens', 'legacyDark', 'legacy']) {
    if (!isRecord(source[field])) fail(`${field}: missing`);
  }
  if (!Array.isArray(source.pairs)) fail('pairs: missing');
  if (!Array.isArray(source.pending)) fail('pending: missing');
  if (errors.length) throw new Error(errors.join('\n'));

  // Axes and dimensions
  const axisDimension = {};
  const dimensionAxis = {};
  for (const [axis, definition] of Object.entries(source.axes)) {
    if (!Array.isArray(definition.dimensions)) {
      fail(`axes.${axis}: dimensions missing`);
      continue;
    }
    for (const dimension of definition.dimensions) {
      if (!source.dimensions[dimension]) fail(`axes.${axis}: unknown dimension ${dimension}`);
      if (dimensionAxis[dimension]) fail(`dimension ${dimension} is in two axes`);
      dimensionAxis[dimension] = axis;
    }
    if (axis !== COLOR_AXIS) {
      if (definition.dimensions.length > 1) fail(`axes.${axis}: only the color axis has more than one dimension`);
      axisDimension[axis] = definition.dimensions[0] || null;
    }
  }
  const color = source.axes[COLOR_AXIS];
  if (!color || JSON.stringify(color.dimensions) !== JSON.stringify(['scheme', 'contrast', 'forcedColors'])) {
    fail('axes.color: dimensions must be scheme, contrast, forcedColors');
  }
  const attributes = new Set();
  for (const [name, dimension] of Object.entries(source.dimensions)) {
    if (!dimensionAxis[name]) fail(`dimensions.${name}: in no axis`);
    if (!Array.isArray(dimension.values) || dimension.values.length === 0) fail(`dimensions.${name}: values missing`);
    else if (!dimension.values.includes(dimension.default)) fail(`dimensions.${name}: default ${dimension.default} isn't a value`);
    if (dimension.attribute !== undefined) {
      if (!/^data-[a-z]+(?:-[a-z]+)*$/.test(dimension.attribute)) fail(`dimensions.${name}: attribute ${dimension.attribute} isn't a data- attribute`);
      if (attributes.has(dimension.attribute)) fail(`dimensions.${name}: attribute ${dimension.attribute} used twice`);
      attributes.add(dimension.attribute);
    } else if (!dimension.media) {
      fail(`dimensions.${name}: needs an attribute or a media query`);
    }
  }
  const scheme = source.dimensions.scheme || {};
  if (!scheme.system || !scheme.attribute) fail('dimensions.scheme: needs an attribute and a system entry');
  else if (!Array.isArray(scheme.values) || JSON.stringify(scheme.values.filter(value => value !== scheme.system.value)) !== JSON.stringify(['light', 'dark'])) {
    fail('dimensions.scheme: values must be light, dark, and the system value');
  }
  for (const name of ['contrast', 'forcedColors']) {
    if (!source.dimensions[name] || !source.dimensions[name].media) fail(`dimensions.${name}: needs a media query`);
  }
  if (errors.length) throw new Error(errors.join('\n'));
  const { dimensions: variantValues, defaults } = variantDimensions(source.dimensions);
  const moreValue = source.dimensions.contrast.media.value;
  const forcedValue = source.dimensions.forcedColors.media.value;

  // Tokens: shape first, then every cell through refs
  const tokens = source.tokens;
  const names = Object.keys(tokens);
  // A token's cells: the ones the output has, the keys its source may use, and the
  // keys it must use. Color-axis tokens have a cell per scheme and contrast (colors
  // add forced); the other axes have one per value of their dimension, written as
  // `default` plus the values that differ.
  const cellsOf = token => {
    if (token.axis === COLOR_AXIS) {
      const output = token.type === 'color' ? [...COLOR_CELLS, FORCED_CELL] : COLOR_CELLS;
      return { output, source: output, required: token.type === 'color' ? ['light', 'dark', FORCED_CELL] : ['light'] };
    }
    const dimension = axisDimension[token.axis];
    const output = dimension ? variantValues[dimension] : [BASE_CELL];
    const others = dimension ? output.filter(value => value !== defaults[dimension]) : [];
    return { output, source: [BASE_CELL, ...others], required: [BASE_CELL] };
  };
  for (const name of names) {
    const token = tokens[name];
    const where = `tokens.${name}`;
    if (!TOKEN_NAME.test(name)) fail(`${where}: not a lowercase custom property name`);
    if (!isRecord(token)) {
      fail(`${where}: not an object`);
      continue;
    }
    if (!TYPES.includes(token.type)) fail(`${where}: unknown type ${token.type}`);
    if (!source.axes[token.axis]) fail(`${where}: unknown axis ${token.axis}`);
    if (!STATUSES.includes(token.status)) fail(`${where}: status must be approved or candidate`);
    if (typeof token.overridable !== 'boolean') fail(`${where}: overridable must be true or false`);
    if (token.overridable && token.type !== 'color') fail(`${where}: only colors can be overridable`);
    if (token.registered !== undefined) {
      if (typeof token.registered !== 'boolean') fail(`${where}: registered must be true or false`);
      else if (token.type !== 'color') fail(`${where}: only colors are registered`);
    }
    if (token.type === 'color' && token.axis !== COLOR_AXIS) fail(`${where}: colors belong to the color axis`);
    if (!isRecord(token.values)) {
      fail(`${where}: values missing`);
      continue;
    }
    if (!source.axes[token.axis]) continue;
    const isColorAxis = token.axis === COLOR_AXIS;
    const cells = cellsOf(token);
    for (const key of Object.keys(token.values)) {
      if (!cells.source.includes(key)) fail(`${where}: unknown cell ${key} (allowed: ${cells.source.join(', ')})`);
    }
    for (const key of cells.required) {
      if (token.values[key] === undefined) fail(`${where}: ${key} value missing`);
    }
    if (isColorAxis && token.values.more !== undefined && token.values.dark !== undefined
      && token.values.darkMore === undefined && entryOf(token.values.more).ref === undefined) {
      fail(`${where}: changes in dark and in contrast-more, so it needs a darkMore value`);
    }
    for (const [cell, raw] of Object.entries(token.values)) {
      const entry = entryOf(raw);
      const at = `${where}.${cell}`;
      if (!isRecord(entry)) {
        fail(`${at}: not a string or an object`);
        continue;
      }
      const hasValue = typeof entry.value === 'string';
      const hasRef = typeof entry.ref === 'string';
      if (hasValue === hasRef) fail(`${at}: needs exactly one of value or ref`);
      for (const key of Object.keys(entry)) {
        if (!['value', 'ref', 'status', 'legacy', 'note'].includes(key)) fail(`${at}: unknown field ${key}`);
      }
      if (entry.status !== undefined && !STATUSES.includes(entry.status)) fail(`${at}: status must be approved or candidate`);
      if (hasRef) {
        const target = tokens[entry.ref];
        if (!target) fail(`${at}: ref ${entry.ref} isn't a token`);
        else if (target.axis !== token.axis || target.type !== token.type) fail(`${at}: ref ${entry.ref} must share the axis and type`);
        if (cell === FORCED_CELL) fail(`${at}: forced values are system colors, not refs`);
      }
      if (hasValue && token.type === 'color') {
        if (cell === FORCED_CELL) {
          if (!design.isSystemColor(entry.value)) fail(`${at}: ${entry.value} isn't a system color`);
        } else if (!/^#(?:[0-9a-f]{6}|[0-9a-f]{8})$/i.test(entry.value) || !design.parseColor(entry.value)) {
          fail(`${at}: ${entry.value} isn't #rrggbb or #rrggbbaa`);
        }
      }
    }
  }
  if (errors.length) throw new Error(errors.join('\n'));

  const pending = source.pending.map(rule => ({ cells: rule.cells || [], types: rule.types || TYPES }));
  const pendingCell = (name, cell) => pending.some(rule => rule.cells.includes(cell) && rule.types.includes(tokens[name].type));

  // The source entry a cell reads, after each axis's fallbacks
  const entryFor = (name, cell) => {
    const values = tokens[name].values;
    const pick = key => (values[key] === undefined ? undefined : entryOf(values[key]));
    if (tokens[name].axis === COLOR_AXIS) {
      if (cell === 'light' || cell === FORCED_CELL) return pick(cell);
      if (cell === 'dark') return pick('dark') || pick('light');
      if (cell === 'more') return pick('more') || pick('light');
      return pick('darkMore') || pick('more') || pick('dark') || pick('light');
    }
    return pick(cell) || pick(BASE_CELL);
  };

  const resolved = {};
  const resolving = new Set();
  const resolve = (name, cell) => {
    const key = `${name}@${cell}`;
    if (resolved[key]) return resolved[key];
    if (resolving.has(key)) throw new Error(`tokens.${name}: ref cycle through ${[...resolving, key].join(' -> ')}`);
    resolving.add(key);
    try {
      const entry = entryFor(name, cell);
      const token = tokens[name];
      let status = entry.status || (pendingCell(name, cell) ? 'candidate' : token.status);
      let value;
      if (entry.ref !== undefined) {
        const target = resolve(entry.ref, cell);
        value = target.value;
        if (target.status === 'candidate') status = 'candidate';
      } else {
        value = entry.value;
      }
      if (token.type === 'color' && cell !== FORCED_CELL) value = design.formatHex(design.parseColor(value));
      resolved[key] = { value, status, ref: entry.ref, legacy: entry.legacy };
      return resolved[key];
    } finally {
      resolving.delete(key);
    }
  };

  const outTokens = {};
  for (const name of names) {
    const token = tokens[name];
    const record = { type: token.type, axis: token.axis, status: token.status, overridable: token.overridable };
    // Colors are registered with @property unless the source says otherwise
    if (token.type === 'color') record.registered = token.registered !== false;
    if (token.role) record.role = token.role;
    record.values = {};
    const candidateCells = [];
    const refs = {};
    for (const cell of cellsOf(token).output) {
      let result;
      try {
        result = resolve(name, cell);
      } catch (e) {
        fail(e.message);
        continue;
      }
      record.values[cell] = result.value;
      if (result.status === 'candidate' && token.status === 'approved') candidateCells.push(cell);
      if (result.ref) refs[cell] = result.ref;
    }
    if (candidateCells.length) record.candidateCells = candidateCells;
    if (Object.keys(refs).length) record.refs = refs;
    outTokens[name] = record;
  }
  // Pairs read resolved cells, so stop here when any cell didn't resolve
  if (errors.length) throw new Error(errors.join('\n'));

  // Pairs
  const ids = new Set();
  const colorToken = name => tokens[name] && tokens[name].type === 'color';
  const pairs = source.pairs.map((pair, index) => {
    const where = `pairs[${index}]${pair && pair.id ? ` ${pair.id}` : ''}`;
    if (!isRecord(pair)) {
      fail(`${where}: not an object`);
      return null;
    }
    for (const key of Object.keys(pair)) {
      if (!['id', 'kind', 'fg', 'bg', 'over', 'inner'].includes(key)) fail(`${where}: unknown field ${key}`);
    }
    if (!PAIR_ID.test(pair.id || '')) fail(`${where}: id must be component/state/part`);
    else if (ids.has(pair.id)) fail(`${where}: duplicate id`);
    ids.add(pair.id);
    if (!KINDS.includes(pair.kind)) fail(`${where}: kind must be ${KINDS.join(', ')}`);
    for (const part of ['fg', 'bg']) {
      if (pair[part] === undefined) fail(`${where}: ${part} missing`);
    }
    for (const part of ['fg', 'bg', 'over', 'inner']) {
      if (pair[part] !== undefined && !colorToken(pair[part])) fail(`${where}: ${part} ${pair[part]} isn't a color token`);
    }
    if (pair.kind === 'focus' && !pair.inner) fail(`${where}: focus pairs name their inner ring`);
    if (pair.kind !== 'focus' && pair.inner) fail(`${where}: only focus pairs have an inner ring`);
    const [component, state, part] = (pair.id || '').split('/');
    const out = { id: pair.id, component, state, part, kind: pair.kind, fg: pair.fg, bg: pair.bg };
    if (pair.over) out.over = pair.over;
    if (pair.inner) out.inner = pair.inner;
    const disabled = state === (source.rules.disabled && source.rules.disabled.state);
    if (colorToken(pair.bg)) {
      const translucent = COLOR_CELLS.some(cell => (outTokens[pair.bg].values[cell] || '').length === 9);
      if ((translucent || disabled) && !pair.over) fail(`${where}: a translucent or disabled pair needs an opaque over`);
    }
    if (pair.over && colorToken(pair.over) && COLOR_CELLS.some(cell => (outTokens[pair.over].values[cell] || '').length === 9)) {
      fail(`${where}: over ${pair.over} must be opaque`);
    }
    return out;
  }).filter(Boolean);

  // Rules: drop the prose, keep what the validator reads
  const rules = JSON.parse(JSON.stringify(source.rules, (key, value) => (key === 'about' ? undefined : value)));
  const ruleTokens = [
    rules.typography && rules.typography.floor,
    rules.targets && rules.targets.token,
    rules.focus && rules.focus.width,
    rules.focus && rules.focus.offset,
    rules.forcedColors && rules.forcedColors.focus && rules.forcedColors.focus.token,
    ...(rules.forcedColors && Array.isArray(rules.forcedColors.boundaries) ? rules.forcedColors.boundaries : [null]),
    rules.disabled && rules.disabled.opacity,
  ];
  ruleTokens.forEach(name => {
    if (!tokens[name]) fail(`rules: ${name} isn't a token`);
  });
  for (const kind of KINDS) {
    if (!rules.ratios || typeof rules.ratios[kind] !== 'number') fail(`rules.ratios.${kind}: missing`);
  }
  // The minimums the validator compares px values against
  const pxRule = (at, value) => {
    if (value === undefined) fail(`${at}: missing`);
    else if (typeof value !== 'string' || !PX_LENGTH.test(value)) fail(`${at}: ${JSON.stringify(value)} isn't a px length`);
  };
  pxRule('rules.targets.minimum', rules.targets && rules.targets.minimum);
  const focus = rules.focus || {};
  if (!isRecord(focus.minimumWidth)) fail('rules.focus.minimumWidth: missing');
  else variantValues.contrast.forEach(value => pxRule(`rules.focus.minimumWidth.${value}`, focus.minimumWidth[value]));
  pxRule('rules.focus.minimumOffset', focus.minimumOffset);
  // Forced colors: CSS Color 4's legible pairs, and the surfaces focus is drawn against
  const forced = rules.forcedColors || {};
  const systemColors = (at, list) => {
    if (!Array.isArray(list) || list.length === 0) fail(`${at}: needs a list of system colors`);
    else list.filter(value => !design.isSystemColor(value)).forEach(value => fail(`${at}: ${value} isn't a system color`));
  };
  if (!isRecord(forced.pairs) || Object.keys(forced.pairs).length === 0) fail('rules.forcedColors.pairs: missing');
  else {
    for (const [background, foregrounds] of Object.entries(forced.pairs)) {
      if (!design.isSystemColor(background)) fail(`rules.forcedColors.pairs: ${background} isn't a system color`);
      systemColors(`rules.forcedColors.pairs.${background}`, foregrounds);
    }
  }
  if (!forced.focus || !design.isSystemColor(forced.focus.value)) fail('rules.forcedColors.focus.value: needs a system color');
  systemColors('rules.forcedColors.focus.surfaces', forced.focus && forced.focus.surfaces);

  // Legacy dark pairs: listed once, and only where dark runs on legacy values
  const legacyPairs = source.legacyDark.pairs;
  if (!Array.isArray(legacyPairs) || !Array.isArray(source.legacyDark.schemes)) fail('legacyDark: needs schemes and pairs');
  else {
    if (new Set(legacyPairs).size !== legacyPairs.length) fail('legacyDark.pairs: duplicate id');
    for (const id of legacyPairs) {
      const pair = pairs.find(candidate => candidate.id === id);
      if (!pair) {
        fail(`legacyDark.pairs: ${id} isn't a pair`);
        continue;
      }
      for (const part of ['fg', 'bg']) {
        const dark = resolved[`${pair[part]}@dark`];
        const fromLegacy = dark && (dark.legacy || (dark.ref && resolved[`${dark.ref}@dark`] && resolved[`${dark.ref}@dark`].legacy));
        if (!fromLegacy) fail(`legacyDark.pairs: ${id} ${part} ${pair[part]} doesn't take a legacy dark value`);
      }
    }
  }
  const aliases = source.legacy.aliases;
  if (!Array.isArray(aliases)) fail('legacy.aliases: missing');
  else {
    const sorted = [...aliases].sort();
    if (JSON.stringify(sorted) !== JSON.stringify(aliases) || new Set(aliases).size !== aliases.length) fail('legacy.aliases: keep it sorted and unique');
    for (const name of aliases) {
      if (!/^--[A-Za-z0-9_-]+$/.test(name)) fail(`legacy.aliases: ${name} isn't a custom property name`);
      if (tokens[name]) fail(`legacy.aliases: ${name} is a token`);
    }
  }
  if (errors.length) throw new Error(errors.join('\n'));

  const dimensions = {};
  for (const [name, dimension] of Object.entries(source.dimensions)) {
    dimensions[name] = JSON.parse(JSON.stringify(dimension, (key, value) => (key === 'about' ? undefined : value)));
  }

  return {
    name: source.name,
    version: source.version,
    axes: source.axes,
    dimensions,
    variants: {
      dimensions: variantValues,
      default: defaults,
      colorAxis: COLOR_AXIS,
      colorCells: {
        light: { [NO_PREFERENCE]: 'light', [moreValue]: 'more' },
        dark: { [NO_PREFERENCE]: 'dark', [moreValue]: 'darkMore' },
      },
      forced: { dimension: 'forcedColors', value: forcedValue, cell: FORCED_CELL },
      axisDimension,
      baseCell: BASE_CELL,
    },
    tokens: outTokens,
    pairs,
    rules,
    legacyDark: { schemes: source.legacyDark.schemes, pairs: legacyPairs },
  };
}

// ---------- CSS ----------

/**
 * Tokens whose value in `cell` differs from `base`
 */
function diff(model, names, cell, base) {
  return names.filter(name => model.tokens[name].values[cell] !== model.tokens[name].values[base]);
}

function declarations(model, names, cell, indent, important = false) {
  return names.map(name => `${indent}${name}: ${model.tokens[name].values[cell]}${important ? ' !important' : ''};`);
}

function block(selector, lines, indent = '') {
  return [`${indent}${selector} {`, ...lines, `${indent}}`].join('\n');
}

function media(query, blocks) {
  return [`@media ${query} {`, blocks.join('\n\n'), '}'].join('\n');
}

function renderCss(model) {
  const names = Object.keys(model.tokens);
  const colorNames = names.filter(name => model.tokens[name].axis === COLOR_AXIS);
  const colors = names.filter(name => model.tokens[name].type === 'color');
  const { scheme, contrast, forcedColors } = model.dimensions;
  const schemeAttr = scheme.attribute;
  const contrastAttr = contrast.attribute;
  const more = contrast.media.value;
  const sections = [`/*\n * ${HEADER.replace(/\n/g, '\n * ')}\n */`];

  // A registered <color> computes a system color to a fixed one, which forced colors
  // then repaint, so a token whose forced keyword has to reach the property it
  // paints stays unregistered
  const unregistered = colors.filter(name => !model.tokens[name].registered);
  sections.push([
    ...(unregistered.length ? [`/* Left unregistered, so a forced system color stays a keyword: ${unregistered.join(', ')} */`] : []),
    colors.filter(name => model.tokens[name].registered).map(name => [
      `@property ${name} {`,
      '  syntax: "<color>";',
      '  inherits: true;',
      `  initial-value: ${model.tokens[name].values.light};`,
      '}',
    ].join('\n')).join('\n\n'),
  ].join('\n'));

  const baseCellOf = name => {
    const token = model.tokens[name];
    if (token.axis === COLOR_AXIS) return 'light';
    const dimension = model.variants.axisDimension[token.axis];
    return dimension ? model.variants.default[dimension] : BASE_CELL;
  };
  sections.push(block(':root', ['  color-scheme: light;', ...names.map(name => `  ${name}: ${model.tokens[name].values[baseCellOf(name)]};`)]));

  // Color. Every rule for the dark-with-more cell outranks or follows the rules it
  // has to beat, so each attribute and media combination lands on one cell.
  const dark = diff(model, colorNames, 'dark', 'light');
  const moreSet = diff(model, colorNames, 'more', 'light');
  const darkMore = colorNames.filter(name => moreSet.includes(name) || model.tokens[name].values.darkMore !== model.tokens[name].values.dark);
  const darkLines = indent => [`${indent}color-scheme: dark;`, ...declarations(model, dark, 'dark', indent)];
  const system = `[${schemeAttr}="${scheme.system.value}"]`;
  const darkAttr = `[${schemeAttr}="dark"]`;
  const moreAttr = `[${contrastAttr}="${more}"]`;
  sections.push('/* Color: dark */\n' + block(`:root${darkAttr}`, darkLines('  ')));
  if (moreSet.length) sections.push('/* Color: contrast more */\n' + block(`:root${moreAttr}`, declarations(model, moreSet, 'more', '  ')));
  if (darkMore.length) sections.push('/* Color: dark with contrast more */\n' + block(`:root${darkAttr}${moreAttr}`, declarations(model, darkMore, 'darkMore', '  ')));
  sections.push('/* Color: the system scheme */\n' + media(scheme.system.media, [
    block(`:root${system}`, darkLines('    '), '  '),
    ...(darkMore.length ? [block(`:root${system}${moreAttr}`, declarations(model, darkMore, 'darkMore', '    '), '  ')] : []),
  ]));
  // The OS contrast setting: light's more values and dark's darkMore values, each
  // written when it changes anything
  const systemContrast = [
    ...(moreSet.length ? [block(':root', declarations(model, moreSet, 'more', '    '), '  ')] : []),
    ...(darkMore.length ? [block(`:root${darkAttr}`, declarations(model, darkMore, 'darkMore', '    '), '  ')] : []),
  ];
  if (systemContrast.length) sections.push('/* Color: the system contrast */\n' + media(contrast.media.query, systemContrast));
  if (darkMore.length) {
    sections.push(media(`${scheme.system.media} and ${contrast.media.query}`, [
      block(`:root${system}`, declarations(model, darkMore, 'darkMore', '    '), '  '),
    ]));
  }
  sections.push('/* Color: forced colors win over every scheme, contrast, and override */\n' + media(forcedColors.media.query, [
    block(':root', declarations(model, colors, FORCED_CELL, '    ', true), '  '),
  ]));

  // One dimension per axis: an attribute block per non-default value, and the
  // same block under the media query that selects that value
  for (const [axis, definition] of Object.entries(model.axes)) {
    if (axis === COLOR_AXIS || definition.dimensions.length === 0) continue;
    const dimension = definition.dimensions[0];
    const source = model.dimensions[dimension];
    const axisNames = names.filter(name => model.tokens[name].axis === axis);
    const base = model.variants.default[dimension];
    const blocks = [];
    for (const value of model.variants.dimensions[dimension]) {
      if (value === base) continue;
      const changed = diff(model, axisNames, value, base);
      if (changed.length === 0) continue;
      blocks.push(block(`:root[${source.attribute}="${value}"]`, declarations(model, changed, value, '  ')));
      if (source.media && source.media.value === value) {
        blocks.push(media(source.media.query, [block(':root', declarations(model, changed, value, '    '), '  ')]));
      }
    }
    if (blocks.length) sections.push(`/* ${definition.label} */\n${blocks.join('\n\n')}`);
  }

  return `${sections.join('\n\n')}\n`;
}

// ---------- JS ----------

function renderJs(model) {
  return [
    ...HEADER.split('\n').map(line => `// ${line}`),
    '',
    '/**',
    ' * Freeze a value and everything in it',
    ' * @template T',
    ' * @param {T} value',
    ' * @returns {T}',
    ' */',
    'function freeze(value) {',
    '  if (value && typeof value === \'object\') {',
    '    Object.values(value).forEach(freeze);',
    '    Object.freeze(value);',
    '  }',
    '  return value;',
    '}',
    '',
    '/** @type {import(\'./contrast.js\').DesignTokenData} */',
    `export const DESIGN_TOKENS = freeze(${JSON.stringify(model, null, 2)});`,
    '',
    'export default DESIGN_TOKENS;',
    '',
  ].join('\n');
}

/**
 * Compile the source and render both outputs
 */
function generate(source, design) {
  const model = compile(source, design);
  return { model, css: renderCss(model), js: renderJs(model) };
}

/**
 * Validate every variant. Returns failures and stale legacy entries as messages.
 */
function check(model, design) {
  const problems = [];
  const failing = new Set();
  for (const variant of design.allVariants(model)) {
    const report = design.validate(model, { variant });
    report.failures.forEach(failure => problems.push(failure.message));
    report.reported.forEach(entry => failing.add(entry.pair));
  }
  for (const id of model.legacyDark.pairs) {
    if (!failing.has(id)) problems.push(`legacyDark.pairs: ${id} passes in every dark variant, so remove it`);
  }
  return [...new Set(problems)];
}

async function main(root = ROOT_DIR) {
  const design = await loadDesign(root);
  let output;
  try {
    output = generate(readSource(root), design);
  } catch (e) {
    console.error(`design tokens: ${SOURCE_PATH} is invalid, nothing written:\n${e.message}`);
    return 1;
  }
  const problems = check(output.model, design);
  if (problems.length) {
    console.error(`design tokens: ${problems.length} validator failure${problems.length === 1 ? '' : 's'}, nothing written:`);
    problems.forEach(problem => console.error(`  ${problem}`));
    return 1;
  }
  fs.writeFileSync(path.join(root, CSS_PATH), output.css);
  fs.writeFileSync(path.join(root, JS_PATH), output.js);
  console.log(`design tokens: wrote ${CSS_PATH} and ${JS_PATH} (${Object.keys(output.model.tokens).length} tokens, ${output.model.pairs.length} pairs)`);
  return 0;
}

if (require.main === module) {
  main().then(code => { process.exitCode = code; }, error => {
    console.error(error);
    process.exitCode = 1;
  });
}

module.exports = { SOURCE_PATH, CSS_PATH, JS_PATH, CONTRAST_PATH, loadDesign, readSource, compile, renderCss, renderJs, generate, check, main };
